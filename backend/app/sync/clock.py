"""Источник серверного времени для синхронизации.

Все места, где требуется серверное время для протокола (TimeSync, execute_at,
server_timestamp), идут через эту утилиту — единая точка для будущей замены
источника без правок по всему коду.
"""

from __future__ import annotations

import time


def server_now_ms() -> float:
    """Текущее серверное время в миллисекундах Unix-эпохи с дробной частью.

    Используется time.time() (wall clock), а не time.monotonic(), потому что:
    1) Протокол фиксирует server_timestamp/execute_at как Unix ms — это нужно
       для согласованности с БД, логами и фронтом.
    2) NTP-алгоритм на клиенте устойчив к редким прыжкам wall clock на сервере:
       такая аномалия резко увеличит RTT измерения и будет отсечена медианным
       фильтром (см. clockMath.selectBestOffset на фронте).
    3) На современных Linux/Windows time.time() имеет микросекундное разрешение,
       чего достаточно с большим запасом для целевой точности 50 мс.
    """
    return time.time() * 1000


